/**
 * 사용자에게 그대로 보여줄, **원인이 이미 분명한 오류**를 만듭니다.
 *
 * 왜 굳이 따로 두나:
 * 소유자는 서버에서 `journalctl` 을 눈으로 훑으며 원인을 찾습니다.
 * 그런데 오류 하나마다 자바스크립트 스택이 20줄씩 붙으면
 * **정작 읽어야 할 한국어 한 줄이 그 사이에 묻힙니다.**
 *
 * 그래서 두 가지를 갈라놓습니다.
 *   · 예상된 오류 (연령 제한 영상, 음성채널 권한 없음 …) → **메시지만** 남긴다
 *   · 예상 못 한 오류 (진짜 버그)                        → 스택을 그대로 남긴다. 고쳐야 하므로
 *
 * 실제로 겪은 일: `/재생` 이 "재생할 수 없는 영상입니다" 로 실패했는데,
 * 로그에는 스택만 잔뜩 보여서 소유자가 원인 줄을 찾지 못했습니다.
 *
 * ⚠️ 코드가 잘못돼서 나는 오류에는 쓰지 마세요. (경로 안전장치, 알 수 없는 설정 키 …)
 *    그건 스택이 있어야 고칠 수 있습니다.
 *
 * @param {string} message 사용자에게 보여줄 한국어 문장 (다음에 뭘 하면 되는지까지)
 */
export function userError(message) {
  const e = new Error(message);
  e.expected = true;
  return e;
}

/** 이 오류를 스택 없이 찍어도 되는가. (index.js 의 logError) */
export function isExpected(err) {
  return Boolean(err?.expected);
}
